#!/usr/bin/env python3
"""
finalize_scaled_results.py — Turn scaled-run results into paper artifacts.

Reads  phase2/reports/per_type_metrics_scaled.json   (written by evaluate.py)
Writes paper/table1.tex (auto-input into main.tex) and regenerates Figure 2.

Usage:
  python3 finalize_scaled_results.py [--json phase2/reports/per_type_metrics_scaled.json]
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PY = sys.executable


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=str(ROOT / "phase2" / "reports" / "per_type_metrics_scaled.json"))
    ap.add_argument("--out-tex", default=str(ROOT / "paper" / "table1.tex"))
    ap.add_argument("--write-scaled-numbers", action="store_true",
                    help="overwrite scaled_numbers.tex from the 300-question "
                         "sample; finalize_fullpool.py owns it by default")
    ap.add_argument("--out-numbers", default=str(ROOT / "paper" / "scaled_numbers.tex"))
    args = ap.parse_args()

    jp = Path(args.json)
    if not jp.exists():
        sys.exit(f"Scaled results JSON not found: {jp}\nThe pipeline writes it after the evaluate step completes.")
    d = json.loads(jp.read_text())

    types = ["known_item", "topical", "bib_fact"]
    modes = ["dense", "bm25", "hybrid", "meta"]
    n = d.get("n_questions", "?")
    pvals = d.get("permutation", {})

    rows = []
    for t in types:
        cell = " & ".join(f"{d['per_type'][t][m]:.3f}" for m in modes)
        rows.append(f"{t.replace('_', chr(92)+'_')} & {cell} \\\\")
    overall = " & ".join(f"{d['overall'][m]:.3f}" for m in modes)

    tex = f"""% table1.tex — AUTO-GENERATED by finalize_scaled_results.py ({n} questions).
\\begin{{tabular}}{{lcccc}}
\\toprule
Question type & dense & bm25 & hybrid & \\textbf{{\\method{{}}}} \\\\
\\midrule
{rows[0]}
\\textbf{{topical}} & {d['per_type']['topical']['dense']:.3f} & {d['per_type']['topical']['bm25']:.3f} & {d['per_type']['topical']['hybrid']:.3f} & \\textbf{{{d['per_type']['topical']['meta']:.3f}}} \\\\
{rows[2]}
\\midrule
\\textbf{{overall}} & {overall} \\\\
\\bottomrule
\\end{{tabular}}
"""
    # table1.tex is likewise owned by finalize_fullpool.py (full pool + CIs).
    # Two generators writing one file made the paper's main table depend on
    # which script ran last.
    if not args.write_scaled_numbers:
        print("skipping table1.tex (owned by finalize_fullpool.py; "
              "pass --write-scaled-numbers to override)")
    else:
        Path(args.out_tex).write_text(tex, encoding="utf-8")
        print(f"Wrote {args.out_tex}")

    # scaled_numbers.tex is owned by finalize_fullpool.py, which measures the
    # whole question pool with bootstrap CIs. This script only ever had the
    # 300-question sample, so running it silently reverted the paper's headline
    # retrieval numbers to the superseded run. Kept behind an explicit flag for
    # reproducing the old sample; never on by default.
    if not args.write_scaled_numbers:
        print("skipping scaled_numbers.tex (owned by finalize_fullpool.py; "
              "pass --write-scaled-numbers to override)")
    else:
        # regenerate paper/scaled_numbers.tex (drives the experiments prose)
        pt = d["per_type"]
        pvals = d.get("permutation", {})
        p_top = pvals.get("topical")

        def fmt_p(p):
            if p is None:
                return r"\TODO{scaled: p-value}"
            return r"$p<0.001$" if p < 0.001 else f"$p={p:.3f}$"

        n_books = d.get("n_books", r"\TODO{scaled: n_books}")
        n_chunks = d.get("n_chunks", r"\TODO{scaled: n_chunks}")

        def numcmd(name, value):
            return r"\newcommand{" + name + r"}{" + str(value) + "}"

        numbers_lines = [
            f"% scaled_numbers.tex - AUTO-GENERATED by finalize_scaled_results.py ({n} questions).",
            numcmd(r"\NBooks", n_books),
            numcmd(r"\NQ", n),
            numcmd(r"\NCorpusChunks", n_chunks),
            numcmd(r"\OverallMeta", f"{d['overall']['meta']:.3f}"),
            numcmd(r"\OverallHybrid", f"{d['overall']['hybrid']:.3f}"),
            numcmd(r"\TopicalMeta", f"{pt['topical']['meta']:.3f}"),
            numcmd(r"\TopicalHybrid", f"{pt['topical']['hybrid']:.3f}"),
            numcmd(r"\TopicalDense", f"{pt['topical']['dense']:.3f}"),
            numcmd(r"\TopicalP", fmt_p(p_top)),
            numcmd(r"\KnownMeta", f"{pt['known_item']['meta']:.3f}"),
            numcmd(r"\KnownHybrid", f"{pt['known_item']['hybrid']:.3f}"),
            numcmd(r"\KnownP", fmt_p(pvals.get("known_item"))),
            numcmd(r"\BibMeta", f"{pt['bib_fact']['meta']:.3f}"),
            numcmd(r"\BibHybrid", f"{pt['bib_fact']['hybrid']:.3f}"),
            numcmd(r"\BibP", fmt_p(pvals.get("bib_fact"))),
            # topical improvement over hybrid, as a relative percentage
            numcmd(r"\TopicalRelGain",
                   f"{100 * (pt['topical']['meta'] / pt['topical']['hybrid'] - 1):.0f}"),
        ]
        Path(args.out_numbers).write_text("\n".join(numbers_lines) + "\n", encoding="utf-8")
        print(f"Wrote {args.out_numbers}")

    # Generation macros (RQ2 / Table 3), from the grounded and no-grounding runs.
    gen_p = ROOT / "phase2" / "reports" / "gen_pass_scaled.json"
    gen_n = ROOT / "phase2" / "reports" / "gen_nogrounding.json"
    if gen_p.exists() and gen_n.exists():
        gp = json.loads(gen_p.read_text())["generation"]
        gn = json.loads(gen_n.read_text())["generation"]["meta"]

        def pct(x):
            return f"{100 * x:.1f}".rstrip("0").rstrip(".")

        gen_lines = ["% gen_numbers.tex - AUTO-GENERATED by finalize_scaled_results.py."]
        for key, tag in (("meta", "Meta"), ("hybrid", "Hybrid")):
            g = gp.get(key)
            if not g:
                continue
            gen_lines += [
                numcmd(rf"\Gen{tag}N", g["n"]),
                numcmd(rf"\Gen{tag}Cite", pct(g["rate_citations"])),
                numcmd(rf"\Gen{tag}Verified", pct(g["rate_verified"])),
                numcmd(rf"\Gen{tag}Faithful", pct(g["rate_faithful"])),
                numcmd(rf"\Gen{tag}Judged", g["n_judged"]),
                numcmd(rf"\Gen{tag}JudgeErr", g["judge_errors"]),
            ]
        gen_lines += [
            numcmd(r"\GenNoGroundFaithful", pct(gn["rate_faithful"])),
            numcmd(r"\GenNoGroundJudged", gn["n_judged"]),
            numcmd(r"\GenNoGroundJudgeErr", gn["judge_errors"]),
        ]
        gen_tex = ROOT / "paper" / "gen_numbers.tex"
        gen_tex.write_text("\n".join(gen_lines) + "\n", encoding="utf-8")
        print(f"Wrote {gen_tex}")
    else:
        print("generation reports incomplete; skipping gen_numbers.tex")

    # LIBRA-CAT macros (written only if the cataloging evaluation has been run)
    cat_json = ROOT / "phase1" / "reports" / "libra_cat_eval.json"
    if cat_json.exists():
        c = json.loads(cat_json.read_text())
        cum, errs, ddc = c["subject_recall_cumulative"], c["predicted_heading_errors"], c["ddc"]
        n_pred = c["n_pred_headings"]
        cat_lines = [
            "% cat_numbers.tex - AUTO-GENERATED by finalize_scaled_results.py.",
            numcmd(r"\CatRecords", c["n_records"]),
            numcmd(r"\CatGoldHeadings", f'{c["n_gold_headings"]:,}'.replace(",", "{,}")),
            numcmd(r"\CatPredHeadings", f'{n_pred:,}'.replace(",", "{,}")),
            numcmd(r"\CatExact", f'{100 * cum["exact"]:.1f}'),
            numcmd(r"\CatSemantic", f'{100 * cum["exact_or_semantic"]:.1f}'),
            numcmd(r"\CatAcceptable", f'{100 * cum["exact_semantic_or_acceptable"]:.1f}'),
            numcmd(r"\CatRecordsAnyExact", f'{100 * c["records_with_any_exact_heading"]:.1f}'),
            numcmd(r"\CatAuthorityViolations", errs.get("authority_violation", 0)),
            numcmd(r"\CatAuthorityRate", f'{100 * errs.get("authority_violation", 0) / n_pred:.1f}'),
            numcmd(r"\CatUnmatched", errs.get("unrelated", 0)),
            numcmd(r"\CatDDCn", ddc["n"]),
            numcmd(r"\CatDDCExact", f'{100 * ddc["exact"]:.1f}'),
            numcmd(r"\CatDDCClass", f'{100 * ddc["class3"]:.1f}'),
            numcmd(r"\CatDDCWrongBranch",
                   f'{100 * ddc["levels"].get("wrong_branch", 0) / ddc["n"]:.1f}'),
        ]
        cat_tex = ROOT / "paper" / "cat_numbers.tex"
        cat_tex.write_text("\n".join(cat_lines) + "\n", encoding="utf-8")
        print(f"Wrote {cat_tex}")
    else:
        print("LIBRA-CAT eval not found; skipping cat_numbers.tex")

    # regenerate Figure 2
    r = subprocess.run([PY, str(ROOT / "figures" / "gen_fig_pertype.py"), "--json", str(jp)])
    print("Figure 2 regenerated" if r.returncode == 0 else "Figure 2 FAILED")

    # significance summary
    print("\nSignificance (meta vs hybrid):")
    for t in types:
        if t in pvals:
            print(f"  {t}: p={pvals[t]:.4f}")
    print("\nNow recompile: cd paper && latexmk -pdf main.tex")


if __name__ == "__main__":
    main()
